import { type Browser, type Page } from "@playwright/test";

import { TWO_FACTOR } from "../playwright.config";
import { expect, test, watchCsp } from "./fixtures";
import { apiPost, dashboardHeading, expectAccessible, nextCode, wrongCode } from "./helpers";

// Two-factor authentication end to end (D-174), on the server where administrators must enrol
// (`PT_REQUIRE_2FA=admins`, e2e/serve.sh two-factor 8715): the first administrator's forced
// enrolment, the two-step login with a wrong code, a used code and a recovery code, the
// roles, an investor's own 2FA with the block after wrong codes, the administrator turning it
// off for the investor and the investor's notice, and the administrator turning off their own
// 2FA, then enrolling again. Each page is checked with axe, and each browser for CSP
// violations (D-163). One test in steps: the server starts empty once per run, and the codes
// of one secret must follow each other (nextCode). Invented names and passwords only.

const ADMIN = {
  username: "guardian",
  password: "two-factor admin password",
  first_name: "Gemma",
  last_name: "Esempio",
};
const INVESTOR = {
  username: "saver",
  password: "two-factor investor pass",
  first_name: "Sara",
  last_name: "Esempio",
};
const CSRF = { "X-Requested-With": "portfolio-tracker" };
// The error that is shown: a page may also hold empty alert regions (e.g. the log out's).
const ALERT = '[role="alert"]:not(:empty)';

/** A browser of its own, in English and UTC, whose CSP violations the test reads itself. */
async function ownBrowser(browser: Browser) {
  const context = await browser.newContext({
    baseURL: TWO_FACTOR,
    locale: "en-US",
    timezoneId: "UTC",
  });
  const violations = await watchCsp(context);
  return { context, violations, page: await context.newPage() };
}

/** The key as the enrolment shows it, without its spaces. */
async function shownSecret(page: Page): Promise<string> {
  const key = (await page.locator(".two-factor-key code").textContent()) ?? "";
  expect(key).toMatch(/^[A-Z2-7 ]{32,}$/);
  return key.replace(/\s/g, "");
}

/** The ten recovery codes as shown once. */
async function shownCodes(page: Page): Promise<string[]> {
  const list = page.getByRole("list", { name: "Recovery codes" });
  await expect(list.getByRole("listitem")).toHaveCount(10);
  const codes = await list.getByRole("listitem").allTextContents();
  for (const code of codes) expect(code).toMatch(/^([A-Za-z0-9]{4}-){3}[A-Za-z0-9]{4}$/);
  return codes;
}

async function password(page: Page, user: { username: string; password: string }) {
  await page.goto("/login");
  await page.getByLabel("Username").fill(user.username);
  await page.getByLabel("Password").fill(user.password);
  await page.getByRole("button", { name: "Log in" }).click();
}

async function logOut(page: Page) {
  await page.getByRole("button", { name: "Log out", exact: true }).click();
  await expect(page.getByLabel("Username")).toBeVisible();
}

async function enrol(page: Page, userPassword: string): Promise<{ secret: string; codes: string[] }> {
  await page.getByLabel("Password").fill(userPassword);
  await page.getByRole("button", { name: "Continue" }).click();
  await expect(page.getByRole("img", { name: "QR code for the authenticator app" })).toBeVisible();
  const secret = await shownSecret(page);
  await page.getByLabel("6-digit code generated by the app").fill(nextCode(secret));
  await page.getByRole("button", { name: "Confirm and turn on" }).click();
  await expect(page.getByRole("heading", { name: "Recovery codes" })).toBeVisible();
  return { secret, codes: await shownCodes(page) };
}

test("two-factor authentication: enrolment, login, roles, turning it off", async ({ browser }) => {
  test.setTimeout(4 * 60_000);
  const admin = await ownBrowser(browser);
  const page = admin.page;
  let adminSecret = "";
  let adminCodes: string[] = [];

  await test.step("the first administrator is taken to the enrolment and cannot skip it", async () => {
    await page.goto("/");
    await page.getByRole("button", { name: "Start from scratch" }).click();
    await page.getByLabel("Username").fill(ADMIN.username);
    await page.getByLabel("First name").fill(ADMIN.first_name);
    await page.getByLabel("Last name").fill(ADMIN.last_name);
    await page.getByLabel("E-mail").fill("guardian@example.org");
    await page.getByLabel("Password", { exact: true }).fill(ADMIN.password);
    await page.getByLabel("Repeat the password").fill(ADMIN.password);
    await page.getByRole("button", { name: "Continue" }).click();
    await page.getByRole("button", { name: "Create the administrator" }).click();

    await expect(
      page.getByRole("heading", { name: "Turn on two-step verification", level: 1 }),
    ).toBeVisible();
    await expect(page).toHaveURL(/\/two-factor-setup$/);
    await expectAccessible(page, "the forced enrolment, password");
    // No way around it: another page leads back here, and the API refuses.
    await page.goto("/accounts");
    await expect(page).toHaveURL(/\/two-factor-setup$/);
    const refused = await page.request.get("/api/v1/accounts");
    expect(refused.status()).toBe(403);
    expect((await refused.json()).code).toBe("TWO_FACTOR_SETUP_REQUIRED");

    await page.getByLabel("Password").fill(ADMIN.password);
    await page.getByRole("button", { name: "Continue" }).click();
    const qr = page.getByRole("img", { name: "QR code for the authenticator app" });
    await expect(qr).toBeVisible();
    expect(await qr.evaluate((el) => el.tagName.toLowerCase())).toBe("svg");
    await expectAccessible(page, "the QR code");
    expect(admin.violations, "CSP on the QR code page").toEqual([]);
    adminSecret = await shownSecret(page);

    // A wrong code first: refused, the QR code stays.
    await page.getByLabel("6-digit code generated by the app").fill(wrongCode(adminSecret));
    await page.getByRole("button", { name: "Confirm and turn on" }).click();
    await expect(page.locator(ALERT)).toContainText("The code is wrong");
    await page.getByLabel("6-digit code generated by the app").fill(nextCode(adminSecret));
    await page.getByRole("button", { name: "Confirm and turn on" }).click();
    await expect(page.getByRole("heading", { name: "Recovery codes", level: 1 })).toBeVisible();
    adminCodes = await shownCodes(page);
    await expectAccessible(page, "the recovery codes");
    await page.getByRole("button", { name: "I saved the codes" }).click();
    await expect(page.getByRole("heading", { name: dashboardHeading(ADMIN), level: 1 })).toBeVisible();
    await page.reload();
    await expect(page.getByRole("heading", { name: dashboardHeading(ADMIN), level: 1 })).toBeVisible();
    await expect(page.getByText(adminCodes[0])).toHaveCount(0); // shown once
  });

  await test.step("the login asks for a code; a wrong or used one is refused", async () => {
    await logOut(page);
    await password(page, ADMIN);
    await expect(page.getByRole("heading", { name: "Two-step verification", level: 1 })).toBeVisible();
    await expectAccessible(page, "the login's second step");
    // No session yet: the proof of the first step opens nothing else.
    expect((await page.request.get("/api/v1/me")).status()).toBe(401);

    await page.getByLabel("Code").fill(wrongCode(adminSecret));
    await page.getByRole("button", { name: "Confirm" }).click();
    await expect(page.locator(ALERT)).toContainText("4 attempts left.");
    const code = nextCode(adminSecret);
    await page.getByLabel("Code").fill(code);
    await page.getByRole("button", { name: "Confirm" }).click();
    await expect(page.getByRole("heading", { name: dashboardHeading(ADMIN), level: 1 })).toBeVisible();

    // The same code works once (D-174 (3)).
    await logOut(page);
    await password(page, ADMIN);
    await page.getByLabel("Code").fill(code);
    await page.getByRole("button", { name: "Confirm" }).click();
    await expect(page.locator(ALERT)).toContainText("4 attempts left.");

    // A recovery code instead.
    await page.getByRole("button", { name: "Lost the app? Use a recovery code." }).click();
    await page.getByLabel("Recovery code").fill(adminCodes[0]);
    await page.getByRole("button", { name: "Confirm" }).click();
    await expect(page.getByRole("heading", { name: dashboardHeading(ADMIN), level: 1 })).toBeVisible();
  });

  const investor = await ownBrowser(browser);
  const theirs = investor.page;
  let investorSecret = "";

  await test.step("an investor is not obliged, and may turn 2FA on in Settings", async () => {
    const created = await apiPost<{ temporary_password: string }>(page, "/admin/users", {
      username: INVESTOR.username,
      first_name: INVESTOR.first_name,
      last_name: INVESTOR.last_name,
      email: "saver@example.org",
      role: "INVESTOR",
    });
    await password(theirs, { username: INVESTOR.username, password: created.temporary_password });
    await theirs.getByLabel("Temporary password").fill(created.temporary_password);
    await theirs.getByLabel("New password", { exact: true }).fill(INVESTOR.password);
    await theirs.getByLabel("Repeat the new password").fill(INVESTOR.password);
    await theirs.getByRole("button", { name: "Change password" }).click();
    await expect(
      theirs.getByRole("heading", { name: dashboardHeading(INVESTOR), level: 1 }),
    ).toBeVisible(); // straight to the dashboard: no enrolment for an investor
    await theirs.goto("/admin");
    await expect(theirs.getByRole("heading", { name: "Page not found" })).toBeVisible();

    await theirs.goto("/settings");
    await theirs.getByRole("button", { name: "Turn on 2FA" }).click();
    const dialog = theirs.getByRole("dialog", { name: "Turn on two-step verification" });
    await dialog.getByLabel("Password").fill(INVESTOR.password);
    await dialog.getByRole("button", { name: "Continue" }).click();
    await expect(dialog.getByRole("heading", { name: "Scan the QR code" })).toBeVisible();
    await expectAccessible(theirs, "Settings, turning 2FA on");
    investorSecret = await shownSecret(theirs);
    await dialog.getByLabel("6-digit code generated by the app").fill(nextCode(investorSecret));
    await dialog.getByRole("button", { name: "Confirm and turn on" }).click();
    await shownCodes(theirs);
    await dialog.getByRole("button", { name: "I saved the codes" }).click();
    await expect(theirs.getByText("Active · 10 recovery codes left")).toBeVisible();
    await expectAccessible(theirs, "Settings with 2FA on");
  });

  await test.step("five wrong codes end the step, then the codes are blocked", async () => {
    await logOut(theirs);
    await password(theirs, INVESTOR);
    for (const left of [4, 3, 2, 1]) {
      await theirs.getByLabel("Code").fill(wrongCode(investorSecret));
      await theirs.getByRole("button", { name: "Confirm" }).click();
      await expect(theirs.locator(ALERT)).toContainText(`${left} attempt${left === 1 ? "" : "s"} left.`);
    }
    await theirs.getByLabel("Code").fill(wrongCode(investorSecret));
    await theirs.getByRole("button", { name: "Confirm" }).click();
    await expect(theirs.getByRole("heading", { name: "Log in", level: 1 })).toBeVisible();
    await expect(theirs.locator(ALERT)).toHaveText(
      "Too many wrong codes: enter your password again.",
    );
    await theirs.getByLabel("Password").fill(INVESTOR.password);
    await theirs.getByRole("button", { name: "Log in" }).click();
    await theirs.getByLabel("Code").fill(nextCode(investorSecret));
    await theirs.getByRole("button", { name: "Confirm" }).click();
    await expect(theirs.locator(ALERT)).toHaveText(/^Too many attempts\. Try again in \d+ minutes?\.$/);
    await expectAccessible(theirs, "the second step, blocked");
  });

  await test.step("the administrator turns the investor's 2FA off; the investor is told", async () => {
    await page.goto("/admin");
    const row = page.getByRole("row").filter({ has: page.getByRole("rowheader", { name: /^saver\b/ }) });
    await expect(row.getByRole("cell", { name: "On", exact: true })).toBeVisible();
    // Never on the administrator's own row.
    const own = page.getByRole("row").filter({ has: page.getByRole("rowheader", { name: /^guardian\b/ }) });
    await expect(own.getByRole("button")).toHaveCount(0);
    await row.getByRole("button", { name: "Turn off the 2FA of saver" }).click();
    const dialog = page.getByRole("dialog", { name: "Turn off the 2FA of saver?" });
    await dialog.getByLabel("Your password").fill(ADMIN.password);
    await dialog.getByLabel("Your code").fill(adminCodes[1]); // a recovery code works here too
    await expectAccessible(page, "the Users screen, turning 2FA off");
    await dialog.getByRole("button", { name: "Turn off 2FA" }).click();
    await expect(page.getByText("The 2FA of saver is off.")).toBeVisible();
    await expect(row.getByRole("cell", { name: "Off", exact: true })).toBeVisible();

    await password(theirs, INVESTOR); // the password alone now
    await expect(
      theirs.getByRole("heading", { name: dashboardHeading(INVESTOR), level: 1 }),
    ).toBeVisible();
    const notice = theirs.getByText(/^Your two-step verification was turned off on .+\. You can turn it on again in Settings\.$/);
    await expect(notice).toBeVisible();
    await expectAccessible(theirs, "the notice after 2FA was turned off");
    await theirs.getByRole("button", { name: "Got it" }).click();
    await expect(notice).toHaveCount(0);
    await theirs.reload();
    await expect(
      theirs.getByRole("heading", { name: dashboardHeading(INVESTOR), level: 1 }),
    ).toBeVisible();
    await expect(notice).toHaveCount(0);
  });

  await test.step("an administrator who turns off their own 2FA must enrol again", async () => {
    await page.goto("/settings");
    await page.getByRole("button", { name: "Turn off 2FA" }).click();
    const dialog = page.getByRole("dialog", { name: "Turn off two-step verification?" });
    await dialog.getByLabel("Password").fill(ADMIN.password);
    await dialog.getByLabel("Code").fill(nextCode(adminSecret));
    await dialog.getByRole("button", { name: "Turn off 2FA" }).click();
    await expect(
      page.getByRole("heading", { name: "Turn on two-step verification", level: 1 }),
    ).toBeVisible();
    await expect(page).toHaveURL(/\/two-factor-setup$/);
    const again = await enrol(page, ADMIN.password);
    expect(again.secret).not.toBe(adminSecret);
    await page.getByRole("button", { name: "I saved the codes" }).click();
    await expect(page.getByRole("heading", { name: dashboardHeading(ADMIN), level: 1 })).toBeVisible();
    // The old recovery codes went with the old secret.
    const old = await page.request.post("/api/v1/me/two-factor/recovery-codes", {
      data: { password: ADMIN.password, recovery_code: adminCodes[2] },
      headers: CSRF,
    });
    expect(old.status()).toBe(422);
  });

  expect(admin.violations, "CSP, the administrator's browser").toEqual([]);
  expect(investor.violations, "CSP, the investor's browser").toEqual([]);
  await investor.context.close();
  await admin.context.close();
});
