import { fireEvent, screen, waitFor, within } from "@testing-library/react";
import { describe, expect, it } from "vitest";

import type { AdminUser } from "../api/types";
import { type Handler, stubFetch } from "../test/fetchStub";
import { HEALTH, ME, NO_ACCOUNTS, renderApp } from "../test/renderApp";

// Managing two-factor authentication (D-174): Settings, the Users screen and the notice after
// an administrator turned it off. Invented users, secrets and codes only.

const SECRET = "ABCDEFGHIJKLMNOPQRSTUVWXYZ234567";
const RECOVERY = Array.from({ length: 10 }, (_, i) => `Ab${i}c-Def${i}-Ghj${i}-Kmn${i}`);
const ON = { two_factor_enabled: true, recovery_codes_left: 7 };
const SESSIONS = {
  body: [
    {
      id: "00000000-0000-4000-8000-000000000501",
      created_at: "2026-10-18T12:00:00Z",
      last_used_at: "2026-10-20T12:00:00Z",
      expires_at: "2026-11-17T12:00:00Z",
      user_agent: null,
      current: true,
    },
  ],
};

const click = (name: string, scope: HTMLElement = document.body) =>
  fireEvent.click(within(scope).getByRole("button", { name }));
const change = (scope: HTMLElement, label: string, value: string) =>
  fireEvent.change(within(scope).getByLabelText(label), { target: { value } });

function cached(client: ReturnType<typeof renderApp>["client"]): string {
  return JSON.stringify([
    client.getMutationCache().getAll().map((m) => [m.state, m.options.mutationKey]),
    client.getQueryCache().getAll().map((q) => [q.queryKey, q.state.data]),
  ]);
}

function settings(me: object, extra: Record<string, Handler> = {}) {
  let user: object = { ...ME, ...me };
  const changed = (next: object) => (user = { ...ME, ...next });
  return stubFetch({
    "GET /api/v1/me": () => ({ body: user }),
    "GET /api/health": HEALTH,
    "GET /api/v1/accounts": NO_ACCOUNTS,
    "GET /api/v1/currencies": { body: ["EUR"] },
    "GET /api/v1/me/sessions": SESSIONS,
    "GET /licenses/frontend.json": { status: 404 },
    "GET /licenses/backend.json": { status: 404 },
    "POST /api/v1/me/two-factor/setup": {
      body: {
        secret: SECRET,
        otpauth_uri: "otpauth://totp/x",
        qr: ["101", "010", "101"],
        digits: 6,
        period: 30,
        server_time: new Date().toISOString(),
      },
    },
    "POST /api/v1/me/two-factor/confirm": () => ({
      body: { user: changed({ ...ON, recovery_codes_left: 10 }), token: null, recovery_codes: RECOVERY },
    }),
    "POST /api/v1/me/two-factor/disable": () => ({ body: { user: changed({}), token: null } }),
    "POST /api/v1/me/two-factor/recovery-codes": () => ({
      body: { user: changed({ ...ON, recovery_codes_left: 10 }), token: null, recovery_codes: RECOVERY },
    }),
    ...extra,
  });
}

const settingsPage = () => screen.findByRole("heading", { name: "Settings", level: 1 });

describe("settings: two-step verification", () => {
  it("turns it on in a dialog: password, QR code, code, then the codes once", async () => {
    const { calls } = settings({});
    const { client } = renderApp("/settings");
    await settingsPage();
    expect(
      screen.getByText("Not active. Recommended if the app can be reached from the Internet."),
    ).toBeInTheDocument();
    click("Turn on 2FA");
    const dialog = await screen.findByRole("dialog", { name: "Turn on two-step verification" });
    change(dialog, "Password", "my password 123");
    click("Continue", dialog);
    expect(await within(dialog).findByRole("heading", { name: "Scan the QR code" })).toHaveFocus();
    expect(within(dialog).getByRole("img", { name: "QR code for the authenticator app" })).toBeInTheDocument();
    change(dialog, "6-digit code generated by the app", "654321");
    click("Confirm and turn on", dialog);
    expect(await within(dialog).findByRole("heading", { name: "Recovery codes" })).toHaveFocus();
    expect(within(dialog).getAllByRole("listitem")).toHaveLength(10);
    expect(cached(client)).not.toContain(RECOVERY[3]);
    expect(cached(client)).not.toContain(SECRET);

    click("I saved the codes", dialog);
    expect(
      await screen.findByText("Two-step verification is on. Your other sessions were logged out."),
    ).toBeInTheDocument();
    expect(screen.queryByRole("dialog")).not.toBeInTheDocument();
    expect(screen.getByText("Active · 10 recovery codes left")).toBeInTheDocument();
    // "Turn on" was replaced: the focus goes to the page's heading.
    await waitFor(() => expect(screen.getByRole("heading", { level: 1 })).toHaveFocus());
    expect(calls.filter((c) => c.path === "/api/v1/me/sessions").length).toBeGreaterThan(1);
  });

  it("turns it off with the password and a code", async () => {
    let attempts = 0;
    const { calls } = settings(ON, {
      "POST /api/v1/me/two-factor/disable": () =>
        ++attempts === 1
          ? { status: 422, body: { code: "TWO_FACTOR_CODE_WRONG", detail: "wrong code" } }
          : { body: { user: ME, token: null } },
    });
    renderApp("/settings");
    await settingsPage();
    expect(screen.getByText("Active · 7 recovery codes left")).toBeInTheDocument();
    click("Turn off 2FA");
    const dialog = await screen.findByRole("dialog", { name: "Turn off two-step verification?" });
    click("Turn off 2FA", dialog);
    expect(within(dialog).getAllByText("Fill in this field.")).toHaveLength(2);
    expect(within(dialog).getByLabelText("Password")).toHaveAttribute("autocomplete", "current-password");
    expect(within(dialog).getByLabelText("Code")).toHaveAttribute("autocomplete", "one-time-code");
    change(dialog, "Password", "my password 123");
    change(dialog, "Code", "111 222");
    click("Turn off 2FA", dialog);
    expect(
      await within(dialog).findByText(
        "The code is wrong, or it was already used. Wait for the next code and try again.",
      ),
    ).toBeInTheDocument();
    expect(within(dialog).getByLabelText("Code")).toHaveValue(""); // a code works once
    change(dialog, "Code", "333444");
    click("Turn off 2FA", dialog);
    expect(await screen.findByText("Two-step verification is off.")).toBeInTheDocument();
    expect(screen.getByRole("button", { name: "Turn on 2FA" })).toBeInTheDocument();
    expect(calls.filter((c) => c.path.endsWith("/disable")).map((c) => c.body)).toEqual([
      { password: "my password 123", code: "111222" },
      { password: "my password 123", code: "333444" },
    ]);
  });

  it("takes an obliged administrator who turns it off back to the enrolment", async () => {
    settings(
      { ...ON, role: "ADMINISTRATOR" },
      {
        "POST /api/v1/me/two-factor/disable": {
          body: { user: { ...ME, role: "ADMINISTRATOR", two_factor_setup_required: true }, token: null },
        },
      },
    );
    const { router } = renderApp("/settings");
    await settingsPage();
    click("Turn off 2FA");
    const dialog = await screen.findByRole("dialog");
    change(dialog, "Password", "my password 123");
    change(dialog, "Code", "123456");
    click("Turn off 2FA", dialog);
    await waitFor(() => expect(router.state.location.pathname).toBe("/two-factor-setup"));
  });

  it("makes new recovery codes, shown once", async () => {
    const { calls } = settings(ON);
    const { client } = renderApp("/settings");
    await settingsPage();
    click("New recovery codes");
    const ask = await screen.findByRole("dialog", { name: "New recovery codes?" });
    change(ask, "Password", "my password 123");
    change(ask, "Code", "Abcd-Efgh-Jkmn-Pqrs");
    click("Create codes", ask);
    const shown = await screen.findByRole("dialog", { name: "Recovery codes" });
    expect(within(shown).getByText(RECOVERY[9])).toBeInTheDocument();
    expect(cached(client)).not.toContain(RECOVERY[9]);
    // Escape does not close it: only "I saved the codes" does.
    fireEvent(shown, new Event("cancel", { cancelable: true }));
    expect(screen.getByRole("dialog", { name: "Recovery codes" })).toBeInTheDocument();
    click("I saved the codes", shown);
    expect(await screen.findByText("New recovery codes saved.")).toBeInTheDocument();
    expect(screen.queryByText(RECOVERY[9])).not.toBeInTheDocument();
    expect(screen.getByText("Active · 10 recovery codes left")).toBeInTheDocument();
    expect(calls.find((c) => c.path.endsWith("/recovery-codes"))?.body).toEqual({
      password: "my password 123",
      recovery_code: "Abcd-Efgh-Jkmn-Pqrs",
    });
  });
});

describe("the notice after an administrator turned it off", () => {
  it("is shown with the date, never by whom, until dismissed", async () => {
    const { calls } = stubFetch({
      "GET /api/v1/me": { body: { ...ME, two_factor_disabled_at: "2026-11-02T10:00:00Z" } },
      "GET /api/health": HEALTH,
      "GET /api/v1/accounts": NO_ACCOUNTS,
      "POST /api/v1/me/two-factor/notice/dismiss": { body: ME },
    });
    renderApp("/accounts");
    const text = await screen.findByText(/was turned off on .*2026\. You can turn it on again/);
    expect(text.textContent).not.toMatch(/administrator/i);
    click("Got it");
    await waitFor(() => expect(screen.queryByText(/was turned off on/)).not.toBeInTheDocument());
    expect(calls.some((c) => c.path === "/api/v1/me/two-factor/notice/dismiss")).toBe(true);
  });
});

describe("users screen: two-step verification", () => {
  const ADMIN = { ...ME, role: "ADMINISTRATOR", ...ON } as const;
  const user = (id: string, username: string, fields: Partial<AdminUser> = {}): AdminUser => ({
    id: `00000000-0000-4000-8000-0000000000${id}`,
    username,
    first_name: "Example",
    last_name: "User",
    email: `${username}@example.org`,
    role: "INVESTOR",
    two_factor_enabled: false,
    must_change_password: false,
    disabled: false,
    created_at: "2026-10-01T09:00:00Z",
    last_login_at: null,
    ...fields,
  });
  const SELF = user("01", "mario", { id: ME.id, role: "ADMINISTRATOR", two_factor_enabled: true });
  const MARTA = user("02", "marta", { two_factor_enabled: true });
  const LUCA = user("03", "luca");

  function admin(extra: Record<string, Handler> = {}) {
    let users = [SELF, MARTA, LUCA];
    return stubFetch({
      "GET /api/v1/me": { body: ADMIN },
      "GET /api/health": HEALTH,
      "GET /api/v1/accounts": NO_ACCOUNTS,
      "GET /api/v1/admin/users": () => ({ body: users }),
      [`POST /api/v1/admin/users/${MARTA.id}/disable-2fa`]: () => {
        const off = { ...MARTA, two_factor_enabled: false };
        users = users.map((u) => (u.id === off.id ? off : u));
        return { body: off };
      },
      ...extra,
    });
  }
  const row = (name: string) =>
    screen.getByRole("rowheader", { name: new RegExp(`^${name}\\b`) }).closest("tr") as HTMLElement;

  it("shows the 2FA column and offers turning it off only on others' rows that have it", async () => {
    admin();
    renderApp("/admin");
    await screen.findByRole("rowheader", { name: /^marta\b/ });
    expect(screen.getByRole("columnheader", { name: "2FA" })).toBeInTheDocument();
    expect(within(row("marta")).getByText("On")).toBeInTheDocument();
    expect(within(row("luca")).getByText("Off")).toBeInTheDocument();
    expect(within(row("mario")).queryByRole("button")).not.toBeInTheDocument();
    expect(within(row("luca")).queryByRole("button", { name: /2FA/ })).not.toBeInTheDocument();
    expect(
      within(row("marta")).getByRole("button", { name: "Turn off the 2FA of marta" }),
    ).toBeInTheDocument();
  });

  it("asks the administrator's password and code, then says it is done", async () => {
    const { calls } = admin();
    const { client } = renderApp("/admin");
    await screen.findByRole("rowheader", { name: /^marta\b/ });
    click("Turn off the 2FA of marta");
    const dialog = await screen.findByRole("dialog", { name: "Turn off the 2FA of marta?" });
    expect(within(dialog).getByText(/lost the phone and the recovery codes/)).toBeInTheDocument();
    change(dialog, "Your password", "the administrator's own");
    change(dialog, "Your code", "123 456");
    click("Turn off 2FA", dialog);
    expect(await screen.findByText("The 2FA of marta is off.")).toBeInTheDocument();
    expect(within(row("marta")).getByText("Off")).toBeInTheDocument();
    expect(calls.find((c) => c.path.endsWith("/disable-2fa"))?.body).toEqual({
      password: "the administrator's own",
      code: "123456",
    });
    expect(cached(client)).not.toContain("the administrator's own");
  });

  it("translates the refusal on one's own row", async () => {
    admin({
      [`POST /api/v1/admin/users/${MARTA.id}/disable-2fa`]: {
        status: 409,
        body: { code: "CANNOT_DISABLE_OWN_2FA", detail: "x" },
      },
    });
    renderApp("/admin");
    await screen.findByRole("rowheader", { name: /^marta\b/ });
    click("Turn off the 2FA of marta");
    const dialog = await screen.findByRole("dialog");
    change(dialog, "Your password", "the administrator's own");
    change(dialog, "Your code", "123456");
    click("Turn off 2FA", dialog);
    expect(
      await within(dialog).findByText("Turn off your own two-step verification from Settings."),
    ).toBeInTheDocument();
  });
});
