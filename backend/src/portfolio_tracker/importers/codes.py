class DuplicateMatch(StrEnum):
    """What an `ALREADY_PRESENT` line has in common with a stored transaction (`match`)."""

    ID = "id"
    EXTERNAL_REF = "external_ref"
    EXTERNAL_REF_AND_TYPE = "external_ref_and_type"


